const LANG_KEY = "praxiproof.lang";

function initialLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch {}
  return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
}

let LANG = initialLang();

function fill(template, vars = {}) {
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

function t(key, vars) {
  const template = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return fill(template, vars);
}

function setLang(lang) {
  LANG = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {}
}

function verdictText(code, params, fallback) {
  if (LANG !== "zh" || !code || !VERDICT_ZH[code]) return fallback;
  const values = { ...params };
  if (values.context && VERDICT_ZH[values.context]) values.context = fill(VERDICT_ZH[values.context], values);
  return fill(VERDICT_ZH[code], values);
}
